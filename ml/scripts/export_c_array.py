#!/usr/bin/env python3
"""
AgriSense - Convert .tflite to C Byte Array Header for TFLite Micro
Generates model_data.h with proper 16-byte alignment and length variable.
"""

import argparse
import sys
from pathlib import Path


def convert_tflite_to_c_array(tflite_path: str, output_path: str, variable_name: str = "g_model_data"):
    src = Path(tflite_path)
    dst = Path(output_path)

    if not src.exists():
        raise FileNotFoundError(f"TFLite model file not found: {src}")

    data = src.read_bytes()
    data_len = len(data)

    guard_name = dst.name.upper().replace(".", "_") + "_"
    lines = [
        "// Auto-generated by AgriSense export_c_array.py",
        f"// Source: {src.name} ({data_len:,} bytes)",
        f"#ifndef {guard_name}",
        f"#define {guard_name}",
        "",
        "#include <cstdint>",
        "",
        f"const unsigned int {variable_name}_len = {data_len};",
        f"alignas(16) const unsigned char {variable_name}[] = {{",
    ]

    for i in range(0, data_len, 12):
        chunk = data[i:i + 12]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        comma = "," if i + 12 < data_len else ""
        lines.append(f"  {hex_str}{comma}")

    lines.append("};")
    lines.append("")
    lines.append(f"#endif // {guard_name}")
    lines.append("")

    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(lines))
    print(f"[AgriSense C Array Export] Converted {src} -> {dst} ({data_len:,} bytes)")


def main():
    parser = argparse.ArgumentParser(description="Convert TFLite model to C++ byte array header.")
    parser.add_argument("--tflite", default="ml/models/model_quant_int8.tflite", help="Input .tflite path")
    parser.add_argument("--output", default="firmware/vision_node/model_data.h", help="Output .h path")
    parser.add_argument("--var-name", default="g_model_data", help="C array variable name")
    args = parser.parse_args()

    convert_tflite_to_c_array(args.tflite, args.output, args.var_name)


if __name__ == "__main__":
    main()
